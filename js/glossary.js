const PARTICLES = /^(이|가|은|는|을|를|의|에|에게|께|께서|와|과|도|로|으로|만|들|아|야|여)?$/;

/** 'ㄹ' 받침이 있는 글자인지 (할, 말, 볼 …) */
const hasRieul = (ch) => {
  const c = ch.charCodeAt(0) - 0xac00;
  return c >= 0 && c < 11172 && c % 28 === 8;
};

function hit(word, [term, , mode]) {
  if (mode instanceof RegExp) return mode.test(word);
  if (mode === 'end') return word.length > term.length && word.endsWith(term);
  if (mode === 'rend') return word.length > term.length && word.endsWith(term) && hasRieul(word[word.length - term.length - 1]);
  if (mode === 'word') return word.startsWith(term) && PARTICLES.test(word.slice(term.length));
  return word.startsWith(term);
}

const SINGLE = ENTRIES.filter(([term]) => !term.includes(' '));
const MULTI = ENTRIES.filter(([term]) => term.includes(' '));

function scan(text, found) {
  for (const word of text.match(/[가-힣]+/g) || []) {
    // 가장 긴 낱말 하나만 (언약궤를 → '언약'이 아니라 '언약궤')
    let best = null;
    for (const e of SINGLE) if (hit(word, e) && (!best || e[0].length > best[0].length)) best = e;
    if (best && !found.has(best[0])) found.set(best[0], { term: best[0], meaning: best[1] });
  }
  for (const [term, meaning] of MULTI) {
    if (!found.has(term) && text.includes(term)) found.set(term, { term, meaning });
  }
  return found;
}

/** 말씀 본문 안의 어려운 단어 [{ term, meaning }] (나온 순서대로) */
export function termsIn(verseText) {
  return [...scan(verseText, new Map()).values()];
}

/** 메모 안에 넣어 둔 말씀(괄호 안)에서 어려운 단어 찾기. 내가 쓴 글은 보지 않는다 */
export function termsInNote(body) {
  const found = new Map();
  for (const m of body.matchAll(/\(([^()]*)\)/g)) scan(m[1], found);
  return [...found.values()];
}
